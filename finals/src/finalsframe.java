    private void loadTable(){
        try {
            int count;
            pst = con.prepareStatement("SELECT * FROM residents");
            
            rs = pst.executeQuery();
            com.mysql.cj.jdbc.result.ResultSetMetaData rss = (com.mysql.cj.jdbc.result.ResultSetMetaData) rs.getMetaData();
            count = rss.getColumnCount();
            DefaultTableModel df = (DefaultTableModel)jTable1.getModel();
            df.setRowCount(0);
            
            while(rs.next()){
                Vector v2 = new Vector();
                for(int a=1; a<=count; a++){
                    v2.add(rs.getString("ID"));
                    v2.add(rs.getString("firstName"));
                    v2.add(rs.getString("middleName"));
                    v2.add(rs.getString("lastName"));
                    v2.add(rs.getString("contact"));
                    v2.add(rs.getString("gender"));
                    v2.add(rs.getString("block"));
                    v2.add(rs.getString("lot"));
                    v2.add(rs.getString("no_residents"));
                }
                df.addRow(v2);
            }
            /**
             * @param args the command line arguments
             */
        } catch (SQLException ex) {
            Logger.getLogger(finalsframe.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
