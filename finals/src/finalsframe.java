    private void insertBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_insertBtnActionPerformed
        // TODO add your handling code here:
        int opt = JOptionPane.showConfirmDialog(rootPane, "Are you sure you want to add this to your database?","Confirmation", JOptionPane.YES_NO_OPTION);
        if(opt == 0){
            try {
                String fname = fnametxt.getText();
                String mname = mnametxt.getText();
                String lname = lnametxt.getText();
                String gender = " ";
                String contactNo = contacttxt.getText();
                String blk = String.valueOf(blockcmbx.getSelectedItem());
                String lot = lotcmbx.getSelectedItem().toString();
                String residents = residentSpr.getValue().toString();
                
                //gender rdoBtns
                if(malerdo.isSelected()){
                    gender = "Male";
                }
                if(femalerdo.isSelected()){
                    gender = "Female";
                }
                pst = con.prepareCall("INSERT INTO residents(ID , firstName, middleName, lastName, contact, gender, block, lot, no_residents )VALUES(?,?,?,?,?,?,?,?,?)");
                pst.setString(1, "0");
                pst.setString(2, fname);
                pst.setString(3, mname);
                pst.setString(4, lname);
                pst.setString(5, contactNo);
                pst.setString(6, gender);
                pst.setString(7, blk);
                pst.setString(8, lot);
                pst.setString(9, residents);
                
                int resp = pst.executeUpdate();
                if(resp == 1){
                    loadTable();
                    JOptionPane.showMessageDialog(this, "Added successfully.");
                }
            } catch (SQLException ex) {
                Logger.getLogger(finalsframe.class.getName()).log(Level.SEVERE, null, ex);
            }
            
            
        }
        
    }//GEN-LAST:event_insertBtnActionPerformed

